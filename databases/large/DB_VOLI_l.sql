DROP DATABASE IF EXISTS DBVOLI_l;
CREATE DATABASE DBVOLI_l;
USE DBVOLI_l;

---------------------------
-- TABELLA AEROPORTI
---------------------------
CREATE TABLE AEROPORTO(
 iata VARCHAR(3) PRIMARY KEY,
 nome VARCHAR(100) NOT NULL,
 continente VARCHAR(50) NOT NULL,
 stato VARCHAR(80) NOT NULL,
 citta VARCHAR(80) NOT NULL,
 passeggeri DECIMAL(5,1) NOT NULL,
 corsie INT NOT NULL
);

---------------------------
-- TABELLA COMPAGNIE AEREE
---------------------------
CREATE TABLE COMPAGNIA(
    nome VARCHAR(100) PRIMARY KEY,
    main_hub VARCHAR(3) NOT NULL,
    CONSTRAINT fk_hub_compagnia 
		FOREIGN KEY (main_hub)
        REFERENCES AEROPORTO(iata)
);

---------------------------
-- DB ROTTE
---------------------------
 CREATE TABLE ROTTA(
	id INT AUTO_INCREMENT PRIMARY KEY,
    iata_partenza VARCHAR(3) NOT NULL,
    iata_arrivo VARCHAR(3) NOT NULL,
    compagnia VARCHAR(30) NOT NULL,
    CONSTRAINT fk_partenza
		FOREIGN KEY (iata_partenza)
        REFERENCES AEROPORTO(iata),
	CONSTRAINT fk_arrivo
		FOREIGN KEY (iata_arrivo)
        REFERENCES AEROPORTO(iata),
	CONSTRAINT fk_compagnia
		FOREIGN KEY (compagnia)
        REFERENCES COMPAGNIA(nome)
);

---------------------------
-- DB VOLI
---------------------------
CREATE TABLE VOLO(
	id INT AUTO_INCREMENT PRIMARY KEY,
    rotta INT NOT NULL,
    modello_aereo VARCHAR(30) NOT NULL,
    timestamp DATETIME NOT NULL,
    
    CONSTRAINT fk_rotta
		FOREIGN KEY (rotta)
        REFERENCES ROTTA(id)
);

