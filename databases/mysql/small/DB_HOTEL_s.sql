    numero VARCHAR(5),
    hotel VARCHAR(100) NOT NULL,
    categoria VARCHAR(30) NOT NULL,
    prezzo INT NOT NULL,
    max_ospiti INT NOT NULL,
    disponibilita ENUM('true', 'false') NOT NULL,
    CONSTRAINT fk_hotel
		FOREIGN KEY(hotel)
        REFERENCES HOTEL(nome)
);

