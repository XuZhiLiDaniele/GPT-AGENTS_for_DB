CREATE TABLE HOTEL(
    nome VARCHAR(100) PRIMARY KEY,
    stato VARCHAR(30) NOT NULL,
    citta VARCHAR(30) NOT NULL,
    indirizzo VARCHAR(60) NOT NULL,
    stelle INT NOT NULL
);

